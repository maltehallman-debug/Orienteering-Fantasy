-- a squad can be changed until the deadline, and league-mates see it from then on
create or replace function public.round_open(r integer) returns boolean
language sql stable set search_path = '' as $$
  select exists(select 1 from public.season_rounds s where s.round = r and now() < coalesce(s.locks_at, s.starts_at))
$$;
